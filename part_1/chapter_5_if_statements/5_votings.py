# Simple If Statements:
age = 18
if age >= 18:
    print("You are eligible to vote!")

# If Else Statements:
age = 17
if age >= 18:
    print("\nYou are eligible to vote!")
else:
    print("\nYou are not eligible as you are younger than 18 years of age!")
    print("Please comeback when you turn 18 years of age!")