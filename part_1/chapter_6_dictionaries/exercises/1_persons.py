# 6-1. Person: Use a dictionary to store information about a person you know. 
# Store their first name, last name, age, and the city in which they live. You 
# should have keys such as first_name, last_name, age, and city. Print each piece  
# of information stored in your dictionary.

person = {
    'first_name': 'Sri Abishek', 
    'last_name': 'Suresh', 
    'age': 27,
    'city': 'chennai',
    }

print(f"The Person's first name is {person['first_name']}")
print(f"The Person's last name is {person['last_name']}")
print(f"The Person's age is {person['age']}")
print(f"The Person's live in {person['city']}")